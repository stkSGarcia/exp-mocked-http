@dataclasses.dataclass
class RequestInfo:
    method: str
    path: str
    route_path: str
    query: str
    host: str
    headers: dict[str, str]
    body: str


@dataclasses.dataclass
class ResponseInfo:
    status_code: int
    headers: dict[str, str]
    body: str


def find_behavior(behaviors: list[Behavior], request: RequestInfo) -> tuple[Behavior, dict[str, str]] | tuple[None, dict[str, str]]:
    for behavior in behaviors:
        if behavior.method != request.method.upper():
            continue
        params = behavior.pattern.match(request.route_path)
        if params is None:
            continue
        if not behavior.condition:
            return behavior, params
        context = build_template_context(request.headers, request.body, request.path, request.query, params)
        try:
            if render_template(behavior.condition, context) == "true":
                return behavior, params
        except TemplateError:
            continue
    return None, {}


def execute_behavior(behavior: Behavior, request: RequestInfo, params: dict[str, str]) -> ResponseInfo:
    context = build_template_context(request.headers, request.body, request.path, request.query, params)
    response: ResponseInfo | None = None
    for action in behavior.actions:
        name, payload = next(iter(action.items()))
        if name == "sleep":
            time.sleep(parse_duration(str(payload["duration"])))
        elif name == "reply_http":
            body = render_template(str(payload.get("body", "")), context)
            headers = {
                str(key): render_template(str(value), context)
                for key, value in (payload.get("headers") or {}).items()
            }
            if not any(key.lower() == "content-type" for key in headers):
                headers["Content-Type"] = "application/json"
            headers["Content-Length"] = str(len(body.encode()))
            response = ResponseInfo(int(payload["status_code"]), headers, body)
    return response or ResponseInfo(204, {"Content-Length": "0"}, "")


def not_found_response() -> ResponseInfo:
    body = "not found"
    return ResponseInfo(
        404,
        {"Content-Type": "text/plain", "Content-Length": str(len(body.encode()))},
        body,
    )


class MockHTTPRequestHandler(BaseHTTPRequestHandler):
    server: "HMockHTTPServer"

    def log_message(self, fmt: str, *args: Any) -> None:
        return

    def do_GET(self) -> None:
        self._handle()

    def do_POST(self) -> None:
        self._handle()

    def do_PUT(self) -> None:
        self._handle()

    def do_PATCH(self) -> None:
        self._handle()

    def do_DELETE(self) -> None:
        self._handle()

    def do_HEAD(self) -> None:
        self._handle(send_body=False)

    def _handle(self, send_body: bool = True) -> None:
        length = int(self.headers.get("Content-Length", "0") or "0")
        body = self.rfile.read(length).decode() if length else ""
        split = urlsplit(self.path)
        route_path = posixpath.normpath(split.path)
        if split.path.startswith("/") and not route_path.startswith("/"):
            route_path = "/" + route_path
        if split.path == "/":
            route_path = "/"
        request = RequestInfo(
            method=self.command,
            path=self.path,
            route_path=route_path,
            query=split.query,
            host=self.headers.get("Host", ""),
            headers={key: value for key, value in self.headers.items()},
            body=body,
        )
        behavior, params = find_behavior(self.server.behaviors, request)
        try:
            response = execute_behavior(behavior, request, params) if behavior else not_found_response()
        except TemplateError as exc:
            self.server.hm_logger.error("template render error", error=str(exc), http_path=request.path)
            response = ResponseInfo(
                500,
                {"Content-Type": "text/plain", "Content-Length": "21"},
                "template render error",
            )
        self.send_response(response.status_code)
        for key, value in response.headers.items():
            self.send_header(key, value)
        self.end_headers()
        if send_body:
            self.wfile.write(response.body.encode())
        self.server.hm_logger.info(
            "http request",
            http_path=request.path,
            http_method=request.method,
            http_host=request.host,
            http_req={
                "headers": request.headers,
                "body": request.body,
            },
            http_res={
                "status_code": response.status_code,
                "headers": response.headers,
                "body": response.body,
            },
        )


class HMockHTTPServer(ThreadingHTTPServer):
    def __init__(self, address: tuple[str, int], behaviors: list[Behavior], logger: JsonLogger) -> None:
        super().__init__(address, MockHTTPRequestHandler)
        self.behaviors = behaviors
        self.hm_logger = logger


def build_server(config: Config | None = None, logger: JsonLogger | None = None) -> HMockHTTPServer:
    config = config or load_config()
    logger = logger or JsonLogger(config.log_level)
    behaviors = load_behaviors(config.templates_dir, logger)
    return HMockHTTPServer((config.http_host, config.http_port), behaviors, logger)


def main() -> None:
    config = load_config()
    logger = JsonLogger(config.log_level)
    server = build_server(config, logger)
    logger.info("hmock server started", host=config.http_host, port=config.http_port)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        logger.info("hmock server stopped")


if __name__ == "__main__":
    main()
